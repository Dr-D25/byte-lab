# Сценарий PowerShell выполняет чтение первых 512 байт физического диска и сохраняет их в отдельный бинарный файл. Полученные данные соответствуют загрузочному сектору диска и могут содержать MBR или VBR в зависимости от конфигурации накопителя. Скрипт предназначен для резервного копирования, исследования структуры загрузочных записей и последующего анализа с помощью специализированных инструментов. Код демонстрирует использование средств .NET в PowerShell для работы с низкоуровневым содержимым устройств хранения данных.


$disk = "\\.\PhysicalDrive0"
$size = 512
$fs = [System.IO.File]::OpenRead($disk)
$buffer = New-Object byte[] $size
$fs.Read($buffer, 0, $size) | Out-Null
[System.IO.File]::WriteAllBytes("C:\mbr_sector.bin", $buffer)
$fs.Close()
